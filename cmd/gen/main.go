// Command gen reads the bundled identity OpenAPI document and the permission catalogue of
// api-specs and writes the route policy table (api/policy_gen.go) and the permission catalogue
// (service/catalogue_gen.go). It is run by `make gen`; its output is committed and never edited.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

func main() {
	spec := flag.String("spec", "", "bundled identity.yaml")
	perms := flag.String("permissions", "", "api-specs common/permissions.yaml")
	commit := flag.String("commit", "unknown", "api-specs commit the inputs came from")
	flag.Parse()
	if *spec == "" || *perms == "" {
		log.Fatal("gen: -spec and -permissions are required")
	}
	must(genPolicies(*spec, *commit))
	must(genCatalogue(*perms, *commit))
}

func must(err error) {
	if err != nil {
		log.Fatal(err)
	}
}

func genPolicies(specPath, commit string) error {
	raw, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}
	var d struct {
		Paths map[string]map[string]map[string]any `yaml:"paths"`
	}
	if err := yaml.Unmarshal(raw, &d); err != nil {
		return err
	}
	type row struct {
		pattern, op, perm, vclass, audit string
		stepUp                           bool
		callers                          []string
	}
	var rows []row
	for path, item := range d.Paths {
		for m, op := range item {
			switch m {
			case "get", "post", "put", "patch", "delete":
			default:
				continue
			}
			r := row{pattern: strings.ToUpper(m) + " " + path, op: str(op["operationId"]), perm: str(op["x-permission"]),
				vclass: str(op["x-vendor-class"]), audit: str(op["x-vendor-audit"])}
			if b, ok := op["x-step-up"].(bool); ok {
				r.stepUp = b
			}
			if cs, ok := op["x-service-callers"].([]any); ok {
				for _, c := range cs {
					r.callers = append(r.callers, str(c))
				}
			}
			if r.op == "" || r.perm == "" {
				return fmt.Errorf("gen: %s has no operationId or x-permission", r.pattern)
			}
			rows = append(rows, r)
		}
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].pattern < rows[j].pattern })
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/gen from api-specs %s; DO NOT EDIT.\n\npackage api\n\n", commit)
	fmt.Fprintf(&b, "// APISpecsCommit is the api-specs commit this table was generated from.\nconst APISpecsCommit = %q\n\n", commit)
	b.WriteString("var routeTable = []routeSpec{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t{Pattern: %q, Op: %q, Permission: %q, StepUp: %v, VendorClass: %q, VendorAudit: %q, Callers: %#v},\n",
			r.pattern, r.op, r.perm, r.stepUp, r.vclass, r.audit, r.callers)
	}
	b.WriteString("}\n")
	return write("api/policy_gen.go", b.Bytes())
}

func genCatalogue(path, commit string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var d struct {
		Version int `yaml:"catalogue_version"`
		Perms   []struct {
			Key, Realm, Service string
			DescriptionKey      string   `yaml:"description_key"`
			Flags               []string `yaml:"flags"`
		} `yaml:"permissions"`
		Roles map[string][]string `yaml:"vendor_roles"`
	}
	if err := yaml.Unmarshal(raw, &d); err != nil {
		return err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/gen from api-specs %s common/permissions.yaml; DO NOT EDIT.\n\npackage service\n\n", commit)
	fmt.Fprintf(&b, "// CatalogueVersion is the catalogue_version of the permission catalogue.\nconst CatalogueVersion = %d\n\n", d.Version)
	b.WriteString("var catalogueEntries = []catalogueEntry{\n")
	for _, p := range d.Perms {
		has := func(f string) bool {
			for _, x := range p.Flags {
				if x == f {
					return true
				}
			}
			return false
		}
		fmt.Fprintf(&b, "\t{Key: %q, Realm: %q, Service: %q, DescriptionKey: %q, Sensitive: %v, StrongOnly: %v, SupportViewable: %v, SupportActable: %v, OwnerGrant: %v},\n",
			p.Key, p.Realm, p.Service, p.DescriptionKey, has("sensitive"), has("strong_only"), has("support_viewable"), has("support_actable"), has("owner_grant"))
	}
	b.WriteString("}\n\n// vendorRolePermissions are the vendor roles of the catalogue.\nvar vendorRolePermissions = map[string][]string{\n")
	names := make([]string, 0, len(d.Roles))
	for n := range d.Roles {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %#v,\n", n, d.Roles[n])
	}
	b.WriteString("}\n")
	return write("service/catalogue_gen.go", b.Bytes())
}

func write(path string, src []byte) error {
	out, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("gen: %s: %w", path, err)
	}
	return os.WriteFile(path, out, 0o644)
}

func str(v any) string {
	s, _ := v.(string)
	return s
}
